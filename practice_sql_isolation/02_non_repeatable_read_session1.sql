-- ============================================================
-- АНОМАЛИЯ 2: NON-REPEATABLE READ (Неповторяемое чтение) — СЕССИЯ 1
-- ============================================================
--
-- Определение:
--   Транзакция T1 дважды читает одну и ту же строку и получает разные
--   результаты, потому что между двумя чтениями другая транзакция T2
--   изменила эту строку и зафиксировала изменения (COMMIT).
--
-- Уровень изоляции при котором возникает: READ COMMITTED (уровень по умолчанию)
-- Решение: повысить уровень до REPEATABLE READ или SERIALIZABLE
--
-- Сценарий: Финансовая проверка клуба. T1 читает трансферный бюджет,
--           делает расчёт, затем снова читает — и получает другое значение!
--
-- ============================================================
-- ПОРЯДОК ЗАПУСКА:
--   1. [Терминал 1] Выполните ШАГ 1 и ШАГ 2
--   2. [Терминал 2] Выполните session2.sql целиком
--   3. [Терминал 1] Выполните ШАГ 3
-- ============================================================

-- Сброс данных
UPDATE accounts SET balance = 1000.00 WHERE name = 'Real_Madrid';

-- ШАГ 1: Начало транзакции на уровне READ COMMITTED
BEGIN;
SET TRANSACTION ISOLATION LEVEL READ COMMITTED;

-- ШАГ 2: Первое чтение бюджета
SELECT name, balance FROM accounts WHERE name = 'Real_Madrid';
-- Результат:
--     name     | balance
-- -------------+---------
--  Real_Madrid | 1000.00

-- Допустим, приложение делает какие-то вычисления на основе этих данных...
-- (имитируем задержку — в это время Сессия 2 выполняет обновление)

-- ===> ПЕРЕКЛЮЧИТЕСЬ В ТЕРМИНАЛ 2 И ВЫПОЛНИТЕ session2.sql ЦЕЛИКОМ <===

-- ШАГ 3: Повторное чтение той же строки в той же транзакции
SELECT name, balance FROM accounts WHERE name = 'Real_Madrid';
-- АНОМАЛИЯ: balance = 2000.00 (другое значение!)
-- Данные изменились, хотя мы ничего не меняли в этой транзакции!
-- Первое и второе чтение вернули разные результаты — это NON-REPEATABLE READ.

COMMIT;

-- Итог: T1 получила разные данные в рамках одной транзакции.
-- Это опасно при расчётах: например, списание суммы может пройти
-- по старому бюджету, хотя он уже изменился.
