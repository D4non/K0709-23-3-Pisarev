-- ============================================================
-- АНОМАЛИЯ 1: DIRTY READ (Грязное чтение) — СЕССИЯ 1
-- ============================================================
--
-- Определение:
--   Транзакция T1 читает данные, которые были изменены транзакцией T2,
--   но T2 ещё не зафиксировала изменения (не выполнила COMMIT).
--   Если T2 выполнит ROLLBACK, T1 уже работала с несуществующими данными.
--
-- Уровень изоляции при котором возникает: READ UNCOMMITTED
--
-- ВАЖНО — особенность PostgreSQL:
--   PostgreSQL НЕ реализует настоящий READ UNCOMMITTED.
--   Даже при SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED
--   PostgreSQL ведёт себя как READ COMMITTED и ПРЕДОТВРАЩАЕТ dirty read.
--   Ниже показано, что PostgreSQL защищает от этой аномалии.
--
-- ============================================================
-- ПОРЯДОК ЗАПУСКА:
--   Терминал 1 (эта сессия) + Терминал 2 (01_dirty_read_session2.sql)
--
--   1. [Терминал 1] Выполните ШАГ 1 и ШАГ 2
--   2. [Терминал 2] Выполните ШАГ 3 (НЕ выполняйте ROLLBACK)
--   3. [Терминал 1] Выполните ШАГ 4
--   4. [Терминал 2] Выполните ШАГ 5 (ROLLBACK)
--   5. [Терминал 1] Выполните ШАГ 6
-- ============================================================

-- Сброс данных к начальному состоянию
UPDATE accounts SET balance = 1000.00 WHERE name = 'Real_Madrid';
SELECT name, balance FROM accounts WHERE name = 'Real_Madrid';

-- ШАГ 1: Начало транзакции с уровнем READ UNCOMMITTED
BEGIN;
SET TRANSACTION ISOLATION LEVEL READ UNCOMMITTED;

-- ШАГ 2: Первое чтение — начальный бюджет Real Madrid
SELECT name, balance FROM accounts WHERE name = 'Real_Madrid';
-- Ожидаемый результат:
--    name     | balance
-- ------------+---------
--  Real_Madrid | 1000.00

-- ===> ПЕРЕКЛЮЧИТЕСЬ В ТЕРМИНАЛ 2, выполните ШАГ 3 (до паузы) <===

-- ШАГ 4: Попытка прочитать незафиксированные данные (dirty read)
SELECT name, balance FROM accounts WHERE name = 'Real_Madrid';
-- PostgreSQL: 1000.00 — АНОМАЛИЯ НЕ ВОЗНИКАЕТ (защита работает!)
-- MySQL/MSSQL с READ UNCOMMITTED: 9999.00 — ГРЯЗНОЕ ЧТЕНИЕ (аномалия!)

-- ===> ПЕРЕКЛЮЧИТЕСЬ В ТЕРМИНАЛ 2, выполните ШАГ 5 (ROLLBACK) <===

-- ШАГ 6: Чтение после ROLLBACK — данные должны остаться корректными
SELECT name, balance FROM accounts WHERE name = 'Real_Madrid';
-- Результат: 1000.00 — данные не испорчены

COMMIT;

-- ВЫВОД: PostgreSQL успешно предотвращает dirty read.
-- При грязном чтении T1 рисковала бы получить значение 9999.00,
-- а после ROLLBACK у T2 — продолжить работу с несуществующими данными.
