-- ============================================================
-- АНОМАЛИЯ 3: PHANTOM READ (Фантомное чтение) — СЕССИЯ 1
-- ============================================================
--
-- Определение:
--   Транзакция T1 дважды выполняет один и тот же запрос с условием
--   фильтрации и получает РАЗНЫЕ НАБОРЫ СТРОК — потому что в промежутке
--   другая транзакция T2 добавила или удалила строки, попадающие под условие.
--   Новые строки называются «фантомами» — они появляются «из ниоткуда».
--
-- Отличие от non-repeatable read:
--   Non-repeatable read: изменилось ЗНАЧЕНИЕ в уже существующей строке
--   Phantom read: изменилось КОЛИЧЕСТВО СТРОК (появились новые или удалены старые)
--
-- Уровень изоляции при котором возникает: READ COMMITTED
-- В PostgreSQL REPEATABLE READ: phantom read тоже предотвращается (MVCC)
-- Решение: SERIALIZABLE (гарантирован стандартом SQL) или REPEATABLE READ в PG
--
-- Сценарий: Отчёт по дорогим заказам атрибутики. T1 считает количество,
--           делает агрегацию — и внезапно появляется новый заказ!
--
-- ============================================================
-- ПОРЯДОК ЗАПУСКА:
--   1. [Терминал 1] Выполните ШАГ 1 и ШАГ 2
--   2. [Терминал 2] Выполните session2.sql целиком
--   3. [Терминал 1] Выполните ШАГ 3
-- ============================================================

-- Сброс: удалить строку, которую добавит Сессия 2 (если запускали ранее)
DELETE FROM orders WHERE product = 'VIP_Box';

-- Начальное состояние: 3 заказа с amount > 100
SELECT COUNT(*) AS total_expensive FROM orders WHERE amount > 100;
-- Ожидается: 3 (VIP_Ticket 1500, Season_Pass 300, Training_Kit 120)

-- ШАГ 1: Начало транзакции
BEGIN;
SET TRANSACTION ISOLATION LEVEL READ COMMITTED;

-- ШАГ 2: Первый запрос — агрегация по дорогим заказам (amount > 100)
SELECT COUNT(*) AS expensive_orders_count FROM orders WHERE amount > 100;
-- Результат: 3

SELECT id, product, amount
FROM orders
WHERE amount > 100
ORDER BY id;
-- Результат:
--  id |   product    | amount
-- ----+--------------+---------
--   1 | VIP_Ticket   | 1500.00
--   4 | Season_Pass  |  300.00
--   5 | Training_Kit |  120.00

-- ===> ПЕРЕКЛЮЧИТЕСЬ В ТЕРМИНАЛ 2 И ВЫПОЛНИТЕ session2.sql ЦЕЛИКОМ <===

-- ШАГ 3: Повторный запрос с тем же условием
SELECT COUNT(*) AS expensive_orders_count FROM orders WHERE amount > 100;
-- ФАНТОМ: 4 (появился 'VIP_Box' за 450.00!)

SELECT id, product, amount
FROM orders
WHERE amount > 100
ORDER BY id;
-- Результат: 4 строки — 'VIP_Box' появился как фантом!
--  id |   product    | amount
-- ----+--------------+---------
--   1 | VIP_Ticket   | 1500.00
--   4 | Season_Pass  |  300.00
--   5 | Training_Kit |  120.00
--   6 | VIP_Box      |  450.00  <-- ФАНТОМНАЯ СТРОКА

COMMIT;

-- Итог: отчёт T1 показал сначала 3 заказа, потом 4.
-- Если T1 считала сумму оборота, первый и второй результаты не совпадут.
