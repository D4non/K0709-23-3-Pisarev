-- ШАГ (Сессия 2): Изменить бюджет Real Madrid и зафиксировать
BEGIN;
SET TRANSACTION ISOLATION LEVEL READ COMMITTED;

UPDATE accounts SET balance = 2000.00 WHERE name = 'Real_Madrid';

COMMIT;
-- Изменение зафиксировано: balance = 2000.00

