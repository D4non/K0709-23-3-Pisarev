-- ============================================================
-- АНОМАЛИЯ 4: LOST UPDATE (Потерянное обновление) — СЕССИЯ 1
-- ============================================================
--
-- Определение:
--   Две транзакции T1 и T2 одновременно читают одно значение,
--   затем обе обновляют его на основе прочитанного.
--   Т2 фиксирует изменения, потом T1 — и ПЕРЕЗАПИСЫВАЕТ результат T2.
--   Обновление T2 теряется, как будто его не было.
--
-- Классический пример: счётчик просмотров матча
--   Начальное значение: 100
--   T1 читает 100, T2 читает 100
--   T2 записывает 100+1=101 и фиксирует
--   T1 записывает 100+1=101 и фиксирует (на основе СТАРОГО значения!)
--   Итог: 101, хотя ожидалось 102. Одно увеличение потеряно!
--
-- Уровень изоляции при котором возникает: READ COMMITTED
-- Решение:
--   1. SELECT FOR UPDATE (блокировка строки)
--   2. Атомарный UPDATE: SET value = value + 1
--   3. REPEATABLE READ с обработкой ошибки сериализации
--
-- ============================================================
-- ПОРЯДОК ЗАПУСКА:
--   1. [Терминал 1] Выполните ШАГ 1 и ШАГ 2
--   2. [Терминал 2] Выполните session2.sql целиком
--   3. [Терминал 1] Выполните ШАГ 3 и ШАГ 4
-- ============================================================

-- Сброс данных
UPDATE counters SET value = 100 WHERE name = 'match_views';
SELECT name, value FROM counters WHERE name = 'match_views';
-- Начальное значение: 100

-- ШАГ 1: Начало транзакции
BEGIN;
SET TRANSACTION ISOLATION LEVEL READ COMMITTED;

-- ШАГ 2: Читаем текущее значение счётчика просмотров матча
SELECT name, value FROM counters WHERE name = 'match_views';
-- Результат: value = 100
-- Приложение сохранило: old_value = 100, new_value = 100 + 1 = 101

-- ===> ПЕРЕКЛЮЧИТЕСЬ В ТЕРМИНАЛ 2 И ВЫПОЛНИТЕ session2.sql ЦЕЛИКОМ <===

-- ШАГ 3: Обновляем счётчик на основе ПРОЧИТАННОГО значения
-- (Сессия 2 уже обновила его до 101 и зафиксировала)
UPDATE counters SET value = 101 WHERE name = 'match_views';
-- Записываем 101 — перезаписываем результат Сессии 2!

COMMIT;

-- ШАГ 4: Проверяем итоговое значение
SELECT name, value FROM counters WHERE name = 'match_views';
-- АНОМАЛИЯ: value = 101 (ожидалось 102!)
-- Оба пользователя увеличили счётчик на 1,
-- но одно увеличение ПОТЕРЯНО.
